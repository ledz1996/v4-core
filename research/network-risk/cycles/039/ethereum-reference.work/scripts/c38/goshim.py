def fnlist(path):
    d = {}
    for l in open(path):
        p = l.split()
        n = ' '.join(p[:-4])
        if n not in d:  # keep the first entry; a later <autogenerated> wrapper of the same name is not the body
            d[n] = (int(p[-4], 16), int(p[-3], 16))
    return d


class Image:
    """Virtual address image of the file-backed sections, built from the ELF section headers."""

    def __init__(self, path):
        f = open(path, 'rb').read()
        self.f = f
        shoff, = struct.unpack_from('<Q', f, 0x28)
        shentsize, shnum = struct.unpack_from('<HH', f, 0x3a)
        self.secs = []
        for i in range(shnum):
            name, typ, flags, addr, off, size = struct.unpack_from('<IIQQQQ', f, shoff + i * shentsize)
            if typ == 1 and addr and (flags & 2):  # PROGBITS, SHF_ALLOC
                self.secs.append((addr, addr + size, off))
        self.secs.sort()
        self.hi = max(h for a, h, o in self.secs)
        self.cache = {}

    def read(self, a, n):
        for lo, hi, off in self.secs:
            if lo <= a and a + n <= hi:
                return int.from_bytes(self.f[off + a - lo: off + a - lo + n], 'little')
        return None


def disasm(binpath, arch, ranges, extra_args=()):
    tool = 'objdump' if arch == 'amd64' else 'llvm-objdump-18'
    out = []
    for lo, hi in ranges:
        args = [tool, '-d', '--no-show-raw-insn', '--start-address=%#x' % lo, '--stop-address=%#x' % hi]
        if arch == 'amd64':
            args += ['-M', 'intel']
        out.append(subprocess.run(args + list(extra_args) + [binpath], capture_output=True, text=True, check=True).stdout)
    return '\n'.join(out)


def collect(arch, fns):
    # cycle 31: every function of the uint256 package is put in the program (the named list stays for reporting),
    # so a helper that one library version keeps out of line (reciprocal2by1, reduce4, Cmp) is modelled too
    allu = sorted(n for n in fns if n.startswith(U) and 'sync/atomic' not in n and 'type:' not in n)
    names = sorted(set([U + n for n in U256_FUNCS if U + n in fns] + allu)) + [VM + h for h in sorted(set(HANDLERS.values()))] + EXTRA.get(arch, []) + [n for n in fns if n.startswith('math/bits.')]
    ranges = {n: fns[n] for n in names if n in fns}
    missing = [n for n in names if n not in fns] + [U + n for n in U256_FUNCS if U + n not in fns]
    stops = {fns[n][0]: n for n in STOPS if n in fns}
    return ranges, missing, stops


