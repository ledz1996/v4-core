"""Shared parts of the Nitro b72783f model runs (cycle 30, theme-nitro-binary-arith-lift).

The release binaries are read as data only: objdump / llvm-objdump print the text of chosen functions, and
constants are read from a virtual-address image built from the ELF section table with Python. Nothing from the
binaries is executed, loaded or mapped executable.

Go register ABI: amd64 args rax, rbx, rcx, rdi, rsi, r8.., g in r14, X15 zero; arm64 args x0.., g in x28.
uint256.Int is [4]uint64 little endian limbs behind a pointer. The core/vm stack object reached by an op handler
is modelled as the build lays it out (read from opMulmod and opLt of both binaries):
  scope+0x8 -> Stack;  Stack+0x8 = item count, Stack+0x10 -> arena;
  arena+0x0 -> data (32 byte slots), arena+0x8 = slot capacity, arena+0x18 = top (number of used slots).
"""
import json, os, re, struct, subprocess

M = (1 << 256) - 1
SIGN = 1 << 255
HERE = os.path.dirname(os.path.abspath(__file__))


def s(x): return x - (1 << 256) if x & SIGN else x
def u(x): return x & M


def ref(op, a, b, c=0):
    if op == 'ADD': return (a + b) & M
    if op == 'MUL': return (a * b) & M
    if op == 'SUB': return (a - b) & M
    if op == 'DIV': return a // b if b else 0
    if op == 'MOD': return a % b if b else 0
    if op == 'SDIV':
        if b == 0: return 0
        q = abs(s(a)) // abs(s(b)); return u(-q if (s(a) < 0) != (s(b) < 0) else q)
    if op == 'SMOD':
        if b == 0: return 0
        r = abs(s(a)) % abs(s(b)); return u(-r if s(a) < 0 else r)
    if op == 'ADDMOD': return (a + b) % c if c else 0
    if op == 'MULMOD': return (a * b) % c if c else 0
    if op == 'EXP': return pow(a, b, 1 << 256)
    if op == 'SIGNEXTEND':
        if a >= 31: return b
        bit = 8 * a + 7
        return (b | (M ^ ((1 << bit) - 1))) if (b >> bit) & 1 else b & ((1 << bit) - 1)
    if op == 'LT': return int(a < b)
    if op == 'GT': return int(a > b)
    if op == 'SLT': return int(s(a) < s(b))
    if op == 'SGT': return int(s(a) > s(b))
    if op == 'EQ': return int(a == b)
    if op == 'ISZERO': return int(a == 0)
    if op == 'BYTE': return 0 if a >= 32 else (b >> (8 * (31 - a))) & 0xff
    if op == 'SHL': return (b << a) & M if a < 256 else 0
    if op == 'SHR': return b >> a if a < 256 else 0
    if op == 'SAR': return u(s(b) >> min(a, 256))
    raise KeyError(op)


