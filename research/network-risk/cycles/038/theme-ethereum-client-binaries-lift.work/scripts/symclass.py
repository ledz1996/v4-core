"""Re-runs symcmp for one binary and attaches the pclntab file:line of every binary-only name, with a class:
autogenerated (compiler wrapper or promoted method), closure (a func literal or an inlined helper named after the
function that holds it), generic (an instantiation of a generic declared in source), or other.
usage: python3 -I symclass.py <binary> <pcln list> <symcmp json>"""
import json, re, sys
b, pc, sj = sys.argv[1:4]
d = json.load(open(sj))
loc = {}
for l in open(pc):
    p = l.split(); name = ' '.join(p[:-4]); loc.setdefault(name, []).append(p[-1])
out = {}
for k, pfx in (('vm', None), ('u256', 'github.com/holiman/uint256.')):
    rows = []
    for n in d[k]['binaryOnly']:
        hits = [(full, f) for full, fs in loc.items() for f in fs if full.endswith('.' + n) or full.endswith('/' + n) or full.endswith(n) and ('core/vm.' + n in full or 'uint256.' + n in full)]
        files = sorted({f for _, f in hits})
        if any('<autogenerated>' in f for f in files) and all('<autogenerated>' in f for f in files):
            c = 'autogenerated'
        elif '[' in n:
            c = 'generic'
        elif re.match(r'^(init|newFrontierInstructionSet|enable\d+|opExtCodeHash|\(\*EVM\)\.\w+)\.', n):
            c = 'closure-or-inlined'
        else:
            c = 'other'
        rows.append({'name': n, 'class': c, 'files': files})
    out[k] = rows
d['binaryOnlyClassified'] = out
json.dump(d, open(sj, 'w'), indent=1)
for k in out:
    for r in out[k]:
        if r['class'] not in ('autogenerated',):
            print(b, k, r['class'], r['name'], r['files'][:3])
