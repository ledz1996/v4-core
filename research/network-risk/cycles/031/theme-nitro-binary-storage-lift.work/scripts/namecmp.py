"""Compares core/state and core/vm function names of the Nitro b72783f binary (pclntab listing) with the
go-ethereum v1.17.10 source files of the same name (downloaded into dl/geth-v1.17.10). usage: python3 -I namecmp.py"""
import re, os, json, glob
B = '/home/user/v4-core/research/network-risk/cycles/030/theme-nitro-binary-arith-lift.work/dl/build/all-amd64.txt'
W = '/home/user/v4-core/research/network-risk/cycles/031/theme-nitro-binary-storage-lift.work/'
src = {}
for pkg in ('state', 'vm'):
    names = set()
    for f in glob.glob(W + 'dl/geth-v1.17.10/core/%s/*.go' % pkg):
        for m in re.finditer(r'^func\s+(?:\(\s*\w*\s*(\*?)\s*(\w+)(?:\[[^\]]*\])?\s*\)\s*)?(\w+)', open(f).read(), re.M):
            star, recv, name = m.groups()
            names.add(('(*%s).%s' % (recv, name)) if star else (('%s.%s' % (recv, name)) if recv else name))
            if recv: names.add('%s.%s' % (recv, name)); names.add('(*%s).%s' % (recv, name))
    src[pkg] = names
out = {'onlyInBinary': {}, 'arbitrumFiles': {}}
for l in open(B):
    p = l.split()
    full, path = ' '.join(p[:-4]), p[-1]
    m = re.match(r'github\.com/ethereum/go-ethereum/core/(state|vm)\.(.*)$', full)
    if not m: continue
    pkg, name = m.groups()
    base = re.sub(r'\.(func|gowrap|deferwrap)\d+(\.\d+)*$', '', name)
    base = re.sub(r'\[.*?\]', '', base)
    if '_arbitrum.go' in path:
        out['arbitrumFiles'].setdefault(pkg, []).append(name + '  ' + path.split('@v1.16.2/')[-1])
    elif base not in src[pkg] and not base.startswith('init') and path != '<autogenerated>:1':
        out['onlyInBinary'].setdefault(pkg, []).append(name + '  ' + path.split('@v1.16.2/')[-1])
json.dump(out, open(W + 'out/namecmp.json', 'w'), indent=1)
for k in out:
    for pkg, v in out[k].items():
        print(k, pkg, len(v))
